// Обрезка текста для строк витрины (90 знаков «Цеха», 120 знаков записи журнала — 2.5): по видимым символам
// (графемам), не по единицам UTF-16 — эмодзи и символ с вариационным селектором на месте разреза не рвутся.
const SEG = new Intl.Segmenter('ru', { granularity: 'grapheme' });

export function cutChars(text, max) {
  const s = String(text ?? '');
  const g = [...SEG.segment(s)].map((x) => x.segment);
  if (g.length <= max) return s;
  return g.slice(0, max - 1).join('').trimEnd() + '…';
}

// Markdown → простой текст для строк витрины (В6): (а) «Ждёт меня», последний текст и «осталось» обрыва PARTIAL,
// строка записи субагента. Снимается до обрезки и до маски. Жирный, курсив, `код`, ссылки → текст ссылки (и картинки →
// подпись), заголовки «#», маркеры списков. Границы слова — явно по буквам и цифрам Unicode (\b на кириллице не
// работает): подчёркивание внутри слова (board_codes, слово_с_подчёркиванием) и «2 * 3» не трогаются.
// Содержимое `кода` не разбирается дальше. Непарный маркер остаётся как есть.
const MD_RULES = [
  [/!?\[([^\]\n]*)\]\([^)\s]*(?:\s+"[^"]*")?\)/gu, '$1'],
  [/(?<![\p{L}\p{N}*])\*\*\*(?=\S)(.+?)(?<=\S)\*\*\*(?![\p{L}\p{N}*])/gu, '$1'],
  [/(?<![\p{L}\p{N}*])\*\*(?=\S)(.+?)(?<=\S)\*\*(?![\p{L}\p{N}*])/gu, '$1'],
  [/(?<![\p{L}\p{N}_])__(?=\S)(.+?)(?<=\S)__(?![\p{L}\p{N}_])/gu, '$1'],
  [/(?<![\p{L}\p{N}*])\*(?=[^\s*])(.+?)(?<=[^\s*])\*(?![\p{L}\p{N}*])/gu, '$1'],
  [/(?<![\p{L}\p{N}_])_(?=[^\s_])(.+?)(?<=[^\s_])_(?![\p{L}\p{N}_])/gu, '$1'],
];
// заголовок «#», маркер списка «-», «*», «+», «1.», «1)» — в начале строки (отступ — только пробелы и табуляция)
const LINE_RULES = [/^[ \t]{0,3}#{1,6}[ \t]+/gmu, /^[ \t]*[-*+][ \t]+/gmu, /^[ \t]*\d{1,3}[.)][ \t]+/gmu];
const CODE = /(`+)([^`\n]+?)\1(?!`)/gu;
const HOLE = /\uE000(\d+)\uE001/gu;

export function stripMarkdown(text) {
  // `код` и ``код`` — содержимое как есть: на время разбора — в метку из символов частной зоны Unicode
  const code = [];
  let t = String(text ?? '').replace(CODE, (_, tick, body) => `\uE000${code.push(body) - 1}\uE001`);
  for (const re of LINE_RULES) t = t.replace(re, '');
  for (const [re, to] of MD_RULES) t = t.replace(re, to);
  return t.replace(HOLE, (_, i) => code[Number(i)]);
}
